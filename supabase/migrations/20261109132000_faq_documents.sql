create table if not exists public.faq_documents (
  id bigint generated by default as identity primary key,
  source text not null unique,
  content text not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.faq_documents enable row level security;
drop policy if exists "faq_documents_public_read" on public.faq_documents;
create policy "faq_documents_public_read" on public.faq_documents for select to anon, authenticated using (active);

