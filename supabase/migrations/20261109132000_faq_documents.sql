create or replace function public.search_faq_documents(search_text text, limit_count integer default 3)
returns table (source text, content text, score integer)
language sql stable security invoker set search_path = public
as $$
  with terms as (
    select regexp_split_to_table(lower(trim(coalesce(search_text, ''))), '[^[:alnum:]àèéìòù]+') as term
  )
  select f.source, f.content,
    (select count(*)::integer from terms where length(term) > 2 and lower(f.content) like '%' || term || '%') as score
  from public.faq_documents f
  where f.active and (trim(coalesce(search_text, '')) = '' or exists (select 1 from terms where length(term) > 2 and lower(f.content) like '%' || term || '%'))
  order by score desc, f.source
  limit greatest(1, least(coalesce(limit_count, 3), 5));
$$;

grant execute on function public.search_faq_documents(text, integer) to anon, authenticated;
