create table if not exists private.chat_events (
  id bigint generated by default as identity primary key,
  session_id uuid not null references private.chat_sessions(id) on delete cascade,
  event_type text not null check (event_type in ('message','cart_change','quote','request')),
  input_chars integer not null default 0,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table private.chat_events enable row level security;
revoke all on private.chat_events from anon, authenticated;

create or replace function public.log_chat_event(p_session_id uuid, p_access_token text, p_event_type text, p_input_chars integer default 0, p_metadata jsonb default '{}'::jsonb)
returns void language plpgsql security definer set search_path = private, public
as $$
declare session_ok boolean;
begin
  select exists(select 1 from private.chat_sessions s where s.id = p_session_id and s.token_hash = encode(extensions.digest(convert_to(p_access_token, 'utf8'), 'sha256'), 'hex') and s.expires_at > now()) into session_ok;
  if not session_ok then raise exception 'Sessione non trovata'; end if;
  insert into private.chat_events(session_id, event_type, input_chars, metadata) values (p_session_id, p_event_type, greatest(0, least(coalesce(p_input_chars, 0), 5000)), coalesce(p_metadata, '{}'::jsonb));
end;
$$;
grant execute on function public.log_chat_event(uuid, text, text, integer, jsonb) to anon, authenticated;
